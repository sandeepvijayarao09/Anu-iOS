#!/usr/bin/env python3
"""Builds the "Anu Alarm" shortcut and embeds it in the app.

iOS lets only the Clock app add alarms to Clock. This shortcut uses Clock's
own "Add Alarm" action, so an alarm Anu sets appears in Clock like any other.
Anu runs it with `shortcuts://x-callback-url/run-shortcut?name=Anu Alarm`
and passes two lines of text: the time ("yyyy-MM-dd HH:mm") and the label.

Run on a Mac (needs `shortcuts sign`):
    python3 Scripts/make_alarm_shortcut.py
It writes Sources/Anu/Tools/BuiltinTools/ClockShortcutFile.swift.
"""
import base64, os, plistlib, subprocess, sys, tempfile, uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Sources/Anu/Tools/BuiltinTools/ClockShortcutFile.swift")
NAME = "Anu Alarm"


def ref(output_uuid, output_name):
    return {"Value": {"OutputUUID": output_uuid, "Type": "ActionOutput", "OutputName": output_name},
            "WFSerializationType": "WFTextTokenAttachment"}


def text_of(output_uuid, output_name):
    return {"Value": {"string": "￼",
                      "attachmentsByRange": {"{0, 1}": {"OutputUUID": output_uuid, "Type": "ActionOutput",
                                                        "OutputName": output_name}}},
            "WFSerializationType": "WFTextTokenString"}


def action(identifier, **params):
    return {"WFWorkflowActionIdentifier": identifier, "WFWorkflowActionParameters": params}


split, first, dates, last = (str(uuid.uuid4()).upper() for _ in range(4))
actions = [
    action("is.workflow.actions.text.split", UUID=split, WFTextSeparator="New Lines",
           text={"Value": {"Type": "ExtensionInput"}, "WFSerializationType": "WFTextTokenAttachment"}),
    action("is.workflow.actions.getitemfromlist", UUID=first, WFItemSpecifier="First Item",
           WFInput=ref(split, "Split Text")),
    action("is.workflow.actions.detect.date", UUID=dates, WFInput=ref(first, "Item from List")),
    action("is.workflow.actions.getitemfromlist", UUID=last, WFItemSpecifier="Last Item",
           WFInput=ref(split, "Split Text")),
    action("com.apple.mobiletimer.CreateAlarmIntent",
           AppIntentDescriptor={"BundleIdentifier": "com.apple.mobiletimer", "AppIntentIdentifier": "CreateAlarmIntent",
                                "Name": "Clock", "TeamIdentifier": "0000000000"},
           dateComponents=ref(dates, "Dates"), name=text_of(last, "Item from List"), allowsSnooze=True),
]
workflow = {
    "WFWorkflowActions": actions,
    "WFWorkflowClientVersion": "3600.0.0",
    "WFWorkflowMinimumClientVersion": 900,
    "WFWorkflowMinimumClientVersionString": "900",
    "WFWorkflowHasShortcutInputVariables": True,
    "WFWorkflowInputContentItemClasses": ["WFStringContentItem"],
    "WFWorkflowIcon": {"WFWorkflowIconStartColor": 463140863, "WFWorkflowIconGlyphNumber": 59511},
    "WFWorkflowImportQuestions": [],
    "WFWorkflowTypes": [],
    "WFWorkflowOutputContentItemClasses": [],
    "WFQuickActionSurfaces": [],
}

with tempfile.TemporaryDirectory() as tmp:
    raw = os.path.join(tmp, "raw.shortcut")
    signed = os.path.join(tmp, f"{NAME}.shortcut")
    with open(raw, "wb") as f:
        plistlib.dump(workflow, f, fmt=plistlib.FMT_BINARY)
    subprocess.run(["shortcuts", "sign", "--mode", "anyone", "--input", raw, "--output", signed], check=True)
    data = open(signed, "rb").read()

b64 = base64.b64encode(data).decode()
lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
body = "\n".join(lines)
swift = f'''// Generated by Scripts/make_alarm_shortcut.py. Do not edit.
import Foundation

extension ClockShortcut {{
    /// The signed "{NAME}" shortcut ({len(data)} bytes).
    static let signedFile = Data(base64Encoded: """
{body}
""", options: .ignoreUnknownCharacters)!
}}
'''
open(OUT, "w").write(swift)
print(f"wrote {OUT} ({len(data)} bytes signed)")
